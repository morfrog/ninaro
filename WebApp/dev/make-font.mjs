// Writes src/render/hersheyFont.ts: the Hershey "Simplex Roman" stroke font
// (futural), used in place of the original's Windows MODERN.FON, which can't
// be shipped. Run once; the output is committed, so the app doesn't depend on
// the font package (whose own dependencies are old).
//
//   npm install --no-save hersheytext@2.0.0
//   node dev/make-font.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const fonts = JSON.parse(readFileSync(require.resolve('hersheytext/hersheytext.json'), 'utf8'));
const chars = fonts.futural.chars; // '!' (33) to '~' (126)

/** "M4,1 L4,22 M4,1 L13,1 16,2" -> [[4,1,4,22],[4,1,13,1,16,2]] */
function strokes(d) {
  return d
    .split('M')
    .filter((s) => s.trim())
    .map((s) => s.replace('L', ' ').trim().split(/[\s,]+/).map(Number));
}

const glyphs = [{ o: 8, s: [] }]; // space: the font has none; 16 units wide, as Simplex's space
for (const c of chars) glyphs.push({ o: Number(c.o), s: strokes(c.d) });

const body = glyphs.map((g, i) => `  /* ${JSON.stringify(String.fromCharCode(32 + i))} */ [${g.o}, ${JSON.stringify(g.s)}],`).join('\n');

writeFileSync(
  new URL('../src/render/hersheyFont.ts', import.meta.url),
  `// Generated by dev/make-font.mjs from hersheytext 2.0.0 (MIT, (c) 2014 James T),
// font "futural": Hershey Simplex Roman, from the Hershey fonts by Dr A. V. Hershey
// (U.S. National Bureau of Standards), which are free to use. Do not edit.
//
// Glyph i is character 32 + i: [half the advance width, strokes]. Each stroke is
// a polyline [x0, y0, x1, y1, ...]; capitals run from y = 1 (top) to 22
// (baseline), descenders to 29.

export type Glyph = readonly [number, readonly (readonly number[])[]];

export const HERSHEY_SIMPLEX: readonly Glyph[] = [
${body}
];
`,
);
console.log(`Wrote ${glyphs.length} glyphs`);
