"""Copy the AI functions out of Legacy/NINARO.C, unchanged, for the golden-game harness.

NINARO.C can't be compiled outside DOS (graphics, mouse, menus), but the AI
in it, RandomMoveFromList and RuleMove, uses only the grid and win checks.
This copies those functions word for word into build/ai_extracted.c, so the
harness runs the 1998 code rather than a retyped copy.

Usage: python extract.py <path to Legacy> <output file>
"""

import re
import sys
from pathlib import Path

FUNCTIONS = ["RandomMoveFromList", "RuleMove"]


def extract(source: str, name: str) -> str:
    match = re.search(rf"^int {name}\(.*?$", source, re.MULTILINE)
    if not match:
        raise SystemExit(f"{name} not found")
    start = match.start()
    brace = source.index("{", start)
    depth = 0
    for i in range(brace, len(source)):
        if source[i] == "{":
            depth += 1
        elif source[i] == "}":
            depth -= 1
            if depth == 0:
                return source[start : i + 1]
    raise SystemExit(f"{name} has no end")


def main() -> None:
    legacy, out = Path(sys.argv[1]), Path(sys.argv[2])
    source = (legacy / "NINARO.C").read_text(encoding="ascii").replace("\r\n", "\n")
    parts = [
        "/* Generated by Tools/golden/extract.py from Legacy/NINARO.C. Do not edit. */",
        '#include "harness.h"',
        "",
    ]
    parts += [extract(source, name) + "\n" for name in FUNCTIONS]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(parts), encoding="ascii")


if __name__ == "__main__":
    main()
